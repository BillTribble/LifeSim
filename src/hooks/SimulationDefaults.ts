export function getStoredSoundMixer(): Record<string, { vol: number; rev: number; oct?: number }> {
  try {
    const stored = localStorage.getItem("soundMixer");
    if (stored) {
      const parsed = JSON.parse(stored);
      const merged: Record<string, { vol: number; rev: number; oct?: number }> = { ...DEFAULTS.soundMixer };
      for (const k of Object.keys(parsed)) {
        merged[k] = { ...(DEFAULTS.soundMixer[k] || { vol: 70, rev: 35, oct: 4 }), ...parsed[k] };
      }
      return merged;
    }
  } catch {}
  return DEFAULTS.soundMixer;
}

export function getStoredFloat(key: string, fallback?: number): number {
  const stored = localStorage.getItem(key);
  if (stored !== null && stored !== "") {
    const val = parseFloat(stored);
    if (!isNaN(val)) {
      if (key === "maxDOMs" && val > 500000) return 100000;
      if (key === "hybridCooldown" && val > 30) return DEFAULTS.hybridCooldown;
      if (key === "minCreatures" && (val === 11 || val === 3 || val === 14 || val === 7 || val === 6 || val === 9)) return DEFAULTS.minCreatures;
      if (key === "maxCreatures" && (val === 5 || val === 12 || val === 14 || val === 15 || val === 19 || val === 7)) return DEFAULTS.maxCreatures;
      if (key === "rotationSpeed" && val === 0.2) return DEFAULTS.rotationSpeed;
      if ((key === "growthSpeed" || key === "extrusionSpeed") && (Math.abs(val - 0.11) < 1e-6 || Math.abs(val - 0.24) < 1e-6)) return DEFAULTS.growthSpeed;
      if ((key === "treeSpeed" || key === "rhizomeSpeed") && Math.abs(val - 0.65) < 1e-6) return DEFAULTS[key];
      if (key === "feelerDelay" && val === 6) return DEFAULTS.feelerDelay;
      if (key === "boundarySize" && (val === 62 || val === 36)) return DEFAULTS.boundarySize;
      if (key === "leafScale" && (Math.abs(val - 0.88) < 1e-6 || Math.abs(val - 0.55) < 1e-6 || Math.abs(val - 0.3) < 1e-6)) return DEFAULTS.leafScale;
      // Ecology-health migrations: legacy stored values that would defeat the clumping fixes
      if (key === "proximity" && val > 100) return DEFAULTS.proximity; // legacy 362 / 484 = whole world
      if (key === "maxMatings" && val === 6) return DEFAULTS.maxMatings; // old default
      if (key === "magnetism" && Math.abs(val - 0.03424424546519402) < 1e-9) return DEFAULTS.magnetism; // old default
      if (key === "hybridStickiness" && Math.abs(val - 27.901245938451485) < 1e-9) return DEFAULTS.hybridStickiness; // old default
      return val;
    }
  }
  return fallback !== undefined ? fallback : DEFAULTS[key];
}

